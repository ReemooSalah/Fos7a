const colorMap: Record<string, string> = {
  green: '#4ADE80', emerald: '#059669', pink: '#F472B6', rose: '#F43F5E',
  indigo: '#818CF8', purple: '#9333EA', yellow: '#FACC15', orange: '#F97316',
  blue: '#60A5FA', cyan: '#06B6D4', amber: '#F59E0B', teal: '#0D9488',
  red: '#F87171', sky: '#38BDF8', violet: '#A78BFA', lime: '#A3E635',
}

function colorFor(cls: string): string {
  for (const k of Object.keys(colorMap)) if (cls.includes(k)) return colorMap[k]
  return '#8B5CF6'
}

export function getCoverColors(gradient: string): { from: string; to: string } {
  const parts = gradient.split(' ')
  return {
    from: colorFor(parts.find(p => p.startsWith('from-')) || ''),
    to: colorFor(parts.find(p => p.startsWith('to-')) || ''),
  }
}

export function getColorFromGradient(gradient: string): string {
  const { from, to } = getCoverColors(gradient)
  return `linear-gradient(135deg, ${from}, ${to})`
}

/** تحويل "5:30" إلى ثوانٍ */
export function durationToSeconds(d: string): number {
  const [m, s] = d.split(':').map(n => parseInt(n, 10) || 0)
  return m * 60 + s
}
